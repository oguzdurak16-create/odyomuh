function cleanLegacyNoise(html = '') {
  return String(html || '')
    .replace(/Yükleniyor\.\.\.\s*Son güncelleme:[^<\n]*/gi, '')
    .replace(/<p[^>]*>\s*Yazan:\s*ODYOMUH\s*<\/p>/gi, '')
    .replace(/<div[^>]*>\s*Yükleniyor\.\.\.\s*Son güncelleme:[\s\S]*?<\/div>/gi, '')
    .trim();
}

export function applyContentOverride(item) {
  if (!item) return item;
  const override = contentOverrides[item.primaryPath] || {};
  const aliases = [...new Set([...(item.searchAliases || []), ...(override.searchAliases || [])])];
  const cleanedHtml = cleanLegacyNoise(item.contentHtml);
  const intro = override.introHtml && !cleanedHtml.includes('search-intent-summary') ? override.introHtml : '';

  return {
    ...item,
    ...override,
    searchAliases: aliases,
    contentHtml: `${intro}${cleanedHtml}`,
  };
}
